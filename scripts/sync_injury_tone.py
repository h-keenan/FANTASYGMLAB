"""Generate the TypeScript copy of modules/injury_tone.py.

    python scripts/sync_injury_tone.py          # write
    python scripts/sync_injury_tone.py --check  # exit 1 on drift
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from modules import injury_tone  # noqa: E402

TARGETS = (
    ROOT / "web-next" / "src" / "lib" / "injuryTone.generated.ts",
    ROOT / "mobile" / "src" / "lib" / "injuryTone.generated.ts",
)

TEMPLATE = """// GENERATED by scripts/sync_injury_tone.py from modules/injury_tone.py. Do not edit.
// The one injury-status -> tone map for web and the app.

export type InjuryToneName = "success" | "warning" | "danger" | "neutral";

const TABLE = __TABLE__ as const;

export const INJURY_TONE_BY_STATUS: Readonly<Record<string, InjuryToneName>> = TABLE.tones as Record<string, InjuryToneName>;
export const INJURY_TONE_GOLDEN: ReadonlyArray<{ status: string; tone: string }> = TABLE.golden;

function normalize(status: string | null | undefined): string {
  return (status ?? "").trim().toLowerCase().replace(/_/g, " ").split(/\\s+/).filter(Boolean).join(" ");
}

/** Whole-status match (never a substring): Out/IR/Doubtful red, Questionable amber, Healthy green, else neutral. */
export function injuryTone(status: string | null | undefined): InjuryToneName {
  return INJURY_TONE_BY_STATUS[normalize(status)] ?? "neutral";
}
"""


def render() -> str:
    return TEMPLATE.replace("__TABLE__", json.dumps(injury_tone.table(), indent=2))


def main(argv: list[str]) -> int:
    expected = render()
    drift = False
    for target in TARGETS:
        if "--check" in argv:
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                print(f"DRIFT: {target.relative_to(ROOT)}")
                drift = True
        else:
            target.write_text(expected, encoding="utf-8")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
