"""Generate the TypeScript copy of modules/trade_value_bands.py.

    python scripts/sync_trade_value_bands.py          # write
    python scripts/sync_trade_value_bands.py --check  # exit 1 on drift

One generated, self-contained file lands in web-next and mobile (identical).
tests/test_trade_value_bands.py fails on drift; the vitest/node tests replay
the golden scores through the TS ladder.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from modules import trade_value_bands  # noqa: E402

TARGETS = (
    ROOT / "web-next" / "src" / "lib" / "tradeValueBands.generated.ts",
    ROOT / "mobile" / "src" / "lib" / "tradeValueBands.generated.ts",
)

TEMPLATE = """// GENERATED by scripts/sync_trade_value_bands.py from modules/trade_value_bands.py. Do not edit.
// The one place a trade score becomes words, a badge and a color token.

export type ValueTone = "success" | "neutral" | "warning" | "danger";

export interface ValueBand {
  id: string;
  verdict: string;
  ui_verdict: string;
  tone: string;
  color_token: ValueTone;
  direction_label: string;
  badge: string;
}

const TABLE = __TABLE__ as const;

export const TRADE_VALUE_CUTS = TABLE.cuts;
export const TRADE_VALUE_BANDS: readonly ValueBand[] = TABLE.bands as unknown as readonly ValueBand[];
export const TRADE_VALUE_GOLDEN: ReadonlyArray<{ score: number; id: string }> = TABLE.golden;

export function bandForScore(score: number): ValueBand {
  const c = TRADE_VALUE_CUTS;
  const pick = (id: string) => TRADE_VALUE_BANDS.find((b) => b.id === id) as ValueBand;
  if (score >= c.smash) return pick("smash");
  if (score >= c.accept) return pick("accept");
  if (score > c.edge) return pick("edge_you");
  if (score >= -c.edge) return pick("even");
  if (score > c.counter) return pick("edge_them");
  if (score > c.decline) return pick("counter");
  if (score > c.hard) return pick("decline");
  return pick("hard");
}

/** The sentence under a verdict, from the same ladder as the verdict. */
export function valueDirectionLabel(score: number): string {
  return bandForScore(score).direction_label;
}

/** Favorable / Fair / Slight Overpay / Major Overpay -> semantic color token. */
export function badgeTone(badge: string | null | undefined): ValueTone {
  const key = (badge || "").trim().toLowerCase();
  const band = TRADE_VALUE_BANDS.find((b) => b.badge.toLowerCase() === key);
  return band ? band.color_token : "neutral";
}
"""


def render() -> str:
    table = json.dumps(trade_value_bands.table(), indent=2)
    return TEMPLATE.replace("__TABLE__", table)


def main(argv: list[str]) -> int:
    expected = render()
    drift = False
    for target in TARGETS:
        if "--check" in argv:
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                print(f"DRIFT: {target.relative_to(ROOT)}")
                drift = True
        else:
            target.write_text(expected, encoding="utf-8")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
