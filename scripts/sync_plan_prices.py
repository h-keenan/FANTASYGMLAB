"""Generate the TypeScript copies of config/plan_prices.json.

    python scripts/sync_plan_prices.py          # write
    python scripts/sync_plan_prices.py --check  # exit 1 on drift

Python reads the JSON directly (modules/stripe_billing.py); the Supabase edge
function and web-next cannot import across the repo, so they get generated
modules. tests/test_plan_prices_sync.py fails if they drift.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "config" / "plan_prices.json"
TARGETS = {
    ROOT / "supabase" / "functions" / "_shared" / "plan_prices.ts": "supabase/functions/_shared",
    ROOT / "web-next" / "src" / "lib" / "planPrices.generated.ts": "web-next/src/lib",
}


def render() -> str:
    plans = json.loads(SOURCE.read_text(encoding="utf-8"))["plans"]
    body = json.dumps(plans, indent=2)
    return (
        "// GENERATED by scripts/sync_plan_prices.py from config/plan_prices.json. Do not edit.\n"
        "// Offline fallback display prices only; live Stripe prices win whenever reachable.\n"
        f"export const FALLBACK_PLAN_PRICES: Record<string, {{ label: string; price: string; cadence: string }}> = {body};\n"
    )


def main(argv: list[str]) -> int:
    expected = render()
    drift = False
    for target in TARGETS:
        if "--check" in argv:
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                print(f"DRIFT: {target.relative_to(ROOT)}")
                drift = True
        else:
            target.write_text(expected, encoding="utf-8")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
