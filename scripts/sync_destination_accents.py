"""Generate the TypeScript copy of modules/destination_accents.py.

    python scripts/sync_destination_accents.py          # write
    python scripts/sync_destination_accents.py --check  # exit 1 on drift
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from modules import destination_accents  # noqa: E402

TARGETS = (
    ROOT / "web-next" / "src" / "lib" / "destinationAccents.generated.ts",
    ROOT / "mobile" / "src" / "lib" / "destinationAccents.generated.ts",
)

TEMPLATE = """// GENERATED by scripts/sync_destination_accents.py from modules/destination_accents.py. Do not edit.
// The one destination -> semantic accent token map for web and the app (nav, GM orb, feature catalog).

export type AccentToken = "accent" | "success" | "warning" | "danger" | "opportunity" | "diagnostic" | "information" | "premium";

const TABLE = __TABLE__ as const;

/** Keyed by feature-catalog id. */
export const ACCENT_BY_DESTINATION: Readonly<Record<string, AccentToken>> = TABLE.accents as Record<string, AccentToken>;

/** A nav / orb row's label as its catalog id: "My Team" -> "my-team". */
export function destinationId(label: string): string {
  return label.trim().toLowerCase().replace(/\\s+/g, "-");
}

/** The accent token for a destination id or label, or `fallback` when it has none (Home, Account, ...). */
export function accentFor(idOrLabel: string, fallback: AccentToken = "accent"): AccentToken {
  return ACCENT_BY_DESTINATION[destinationId(idOrLabel)] ?? fallback;
}
"""


def render() -> str:
    return TEMPLATE.replace("__TABLE__", json.dumps(destination_accents.table(), indent=2))


def main(argv: list[str]) -> int:
    expected = render()
    drift = False
    for target in TARGETS:
        if "--check" in argv:
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                print(f"DRIFT: {target.relative_to(ROOT)}")
                drift = True
        else:
            target.write_text(expected, encoding="utf-8")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
