const {
  withDangerousMod,
  withEntitlementsPlist,
  withInfoPlist,
  withXcodeProject,
} = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * iOS Live Activities + home-screen widget (WidgetKit extension target).
 *
 * OFF BY DEFAULT: does nothing unless FANTASYDESK_LIVE_ACTIVITIES=1 is set in
 * the environment at `expo prebuild` time, so the production build pipeline is
 * untouched until a human flips it (needs App Group + provisioning first; see
 * docs/live-activities-widgets-plan.md).
 *
 * Sources live in mobile/native/live-activity/{widgets,bridge}; they are copied
 * into the generated ios/ project (which is regenerated by prebuild --clean).
 */

const SRC_ROOT = path.join(__dirname, '..', 'native', 'live-activity');
const EXT_NAME = 'FantasyDeskWidgets';
const BRIDGE_DIR = 'FantasyDeskLiveActivity';
const APP_GROUP = 'group.com.fantasygmlab.app';
const SHARED = 'FantasyDeskActivityAttributes.swift';
const EXT_SWIFT = [
  SHARED,
  'FantasyDeskWidgetBundle.swift',
  'FantasyDeskLiveActivityWidget.swift',
  'FantasyDeskAlertsWidget.swift',
];
const BRIDGE_FILES = [SHARED, 'FantasyDeskLiveActivityModule.swift', 'FantasyDeskLiveActivityModule.m'];

function isEnabled() {
  return process.env.FANTASYDESK_LIVE_ACTIVITIES === '1';
}

function copyInto(destDir, files, fromSub) {
  fs.mkdirSync(destDir, { recursive: true });
  for (const f of files) {
    const from = f === SHARED ? path.join(SRC_ROOT, 'widgets', f) : path.join(SRC_ROOT, fromSub, f);
    fs.copyFileSync(from, path.join(destDir, f));
  }
}

function unquote(v) {
  return typeof v === 'string' ? v.replace(/^"|"$/g, '') : v;
}

function hasTarget(proj) {
  return Object.values(proj.pbxNativeTargetSection()).some(
    (t) => t && typeof t === 'object' && unquote(t.name) === EXT_NAME,
  );
}

/** Pure(ish) project mutation; exported so it can be exercised against a parsed pbxproj in tests. */
function addTargets(proj, { projectName, bundleId }) {
  if (hasTarget(proj)) return proj; // idempotent
  const mainUuid = proj.getFirstTarget().uuid;
  const mainGroupKey = proj.getFirstProject().firstProject.mainGroup;

  // ---- main app target: bridge sources
  const bridgeGroup = proj.addPbxGroup([], BRIDGE_DIR, BRIDGE_DIR);
  proj.addToPbxGroup(bridgeGroup.uuid, mainGroupKey);
  for (const f of BRIDGE_FILES) {
    proj.addSourceFile(`${BRIDGE_DIR}/${f}`, { target: mainUuid }, bridgeGroup.uuid);
  }

  // ---- extension target
  const ext = proj.addTarget(EXT_NAME, 'app_extension', EXT_NAME, `${bundleId}.widgets`);
  const extGroup = proj.addPbxGroup([...EXT_SWIFT, 'Info.plist', `${EXT_NAME}.entitlements`], EXT_NAME, EXT_NAME);
  proj.addToPbxGroup(extGroup.uuid, mainGroupKey);
  proj.addBuildPhase(EXT_SWIFT.map((f) => `${EXT_NAME}/${f}`), 'PBXSourcesBuildPhase', 'Sources', ext.uuid);
  proj.addBuildPhase([], 'PBXResourcesBuildPhase', 'Resources', ext.uuid);
  proj.addBuildPhase([], 'PBXFrameworksBuildPhase', 'Frameworks', ext.uuid);
  proj.addFramework('WidgetKit.framework', { target: ext.uuid, link: true });
  proj.addFramework('SwiftUI.framework', { target: ext.uuid, link: true });

  // Extension build settings (addTarget's defaults point at a non-existent Info.plist name).
  const mainSettings = Object.values(proj.pbxXCBuildConfigurationSection()).find(
    (c) => c && c.buildSettings && unquote(c.buildSettings.PRODUCT_BUNDLE_IDENTIFIER) === bundleId,
  );
  const team = mainSettings && mainSettings.buildSettings.DEVELOPMENT_TEAM;
  const cfgList = proj.pbxXCConfigurationList()[ext.pbxNativeTarget.buildConfigurationList];
  for (const ref of cfgList.buildConfigurations) {
    const s = proj.pbxXCBuildConfigurationSection()[ref.value].buildSettings;
    s.INFOPLIST_FILE = `"${EXT_NAME}/Info.plist"`;
    s.CODE_SIGN_ENTITLEMENTS = `"${EXT_NAME}/${EXT_NAME}.entitlements"`;
    s.IPHONEOS_DEPLOYMENT_TARGET = '16.2';
    s.SWIFT_VERSION = '5.0';
    s.TARGETED_DEVICE_FAMILY = '"1,2"';
    s.MARKETING_VERSION = '1.0';
    s.CURRENT_PROJECT_VERSION = '1';
    s.GENERATE_INFOPLIST_FILE = 'NO';
    s.ASSETCATALOG_COMPILER_GLOBAL_ACCENT_COLOR_NAME = 'AccentColor';
    if (team) s.DEVELOPMENT_TEAM = team;
  }

  // ---- embed the .appex in the app + build-order dependency
  const productRef = ext.pbxNativeTarget.productReference;
  const buildFiles = proj.pbxBuildFileSection();
  const productBuildFileKey = Object.keys(buildFiles).find(
    (k) => !k.endsWith('_comment') && buildFiles[k].fileRef === productRef,
  );
  const embed = proj.addBuildPhase([], 'PBXCopyFilesBuildPhase', 'Embed Foundation Extensions', mainUuid, 'app_extension');
  embed.buildPhase.files.push({ value: productBuildFileKey, comment: `${EXT_NAME}.appex in Embed Foundation Extensions` });
  // xcode's addTargetDependency silently no-ops when these sections are absent
  // (a fresh Expo project has no dependencies yet).
  const objects = proj.hash.project.objects;
  objects.PBXTargetDependency = objects.PBXTargetDependency || {};
  objects.PBXContainerItemProxy = objects.PBXContainerItemProxy || {};
  proj.addTargetDependency(mainUuid, [ext.uuid]);
  return proj;
}

module.exports = function withLiveActivities(config) {
  if (!isEnabled()) return config;

  config = withInfoPlist(config, (c) => {
    c.modResults.NSSupportsLiveActivities = true;
    c.modResults.NSSupportsLiveActivitiesFrequentUpdates = false;
    return c;
  });

  config = withEntitlementsPlist(config, (c) => {
    const groups = new Set(c.modResults['com.apple.security.application-groups'] || []);
    groups.add(APP_GROUP);
    c.modResults['com.apple.security.application-groups'] = [...groups];
    return c;
  });

  config = withDangerousMod(config, [
    'ios',
    (c) => {
      const root = c.modRequest.platformProjectRoot;
      copyInto(path.join(root, EXT_NAME), [...EXT_SWIFT, 'Info.plist', `${EXT_NAME}.entitlements`], 'widgets');
      copyInto(path.join(root, BRIDGE_DIR), BRIDGE_FILES, 'bridge');
      return c;
    },
  ]);

  config = withXcodeProject(config, (c) => {
    addTargets(c.modResults, {
      projectName: c.modRequest.projectName,
      bundleId: c.ios && c.ios.bundleIdentifier,
    });
    return c;
  });

  return config;
};

module.exports.addTargets = addTargets;
module.exports.hasTarget = hasTarget;
module.exports.isEnabled = isEnabled;
